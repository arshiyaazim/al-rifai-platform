'use client';

import {Download, FileText} from 'lucide-react';
import {useState} from 'react';
import {toast} from 'sonner';
import {bdtNumber, dateDdMmYyyy, dhakaDateTime, todayStamp} from '@/lib/export-format';
import type {CashTransaction, CashTransactionPage} from './cash-transactions-table';

type Filters = {from: string; to: string; amountMin: string; amountMax: string};

function query(filters: Filters) {
  const params = new URLSearchParams({page: '1', limit: '10000'});
  if (filters.from) params.set('from', filters.from);
  if (filters.to) params.set('to', filters.to);
  if (filters.amountMin) params.set('amountMin', String(Math.round(Number(filters.amountMin) * 100)));
  if (filters.amountMax) params.set('amountMax', String(Math.round(Number(filters.amountMax) * 100)));
  return params;
}

function periodLabel(filters: Filters) {
  if (filters.from && filters.to) return `${dateDdMmYyyy(filters.from)} → ${dateDdMmYyyy(filters.to)}`;
  if (filters.from) return `From ${dateDdMmYyyy(filters.from)}`;
  if (filters.to) return `Through ${dateDdMmYyyy(filters.to)}`;
  return 'All time';
}

export function EmployeeStatementExport({
  employeeId, name, designation, dateOfJoin, totalPayouts, totalPaidMinor,
  filters, generatedBy,
}: {
  employeeId: string;
  name: string;
  designation: string | null;
  dateOfJoin: string | null;
  totalPayouts: number;
  totalPaidMinor: string;
  filters: Filters;
  generatedBy: string;
}) {
  const [busy, setBusy] = useState<'csv' | 'pdf' | null>(null);

  async function loadTransactions(): Promise<CashTransaction[]> {
    const response = await fetch(
      `/api/cash/employees/${encodeURIComponent(employeeId)}/transactions?${query(filters).toString()}`,
      {headers: {accept: 'application/json'}, cache: 'no-store'},
    );
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const payload = await response.json() as CashTransactionPage;
    return payload.transactions;
  }

  function summaryRows(rows: CashTransaction[]) {
    const paid = rows
      .filter((row) => row.state !== 'REVERSED')
      .reduce((sum, row) => sum + Number(row.amountMinor), 0);
    return {
      count: rows.filter((row) => row.state !== 'REVERSED').length || totalPayouts,
      paidMinor: rows.length ? String(paid) : totalPaidMinor,
      period: periodLabel(filters),
    };
  }

  async function exportCsv() {
    setBusy('csv');
    try {
      const transactions = await loadTransactions();
      const summary = summaryRows(transactions);
      const lines: string[][] = [
        ['AL-RIFA\'I Platform — Employee Cash Statement'],
        ['Employee Name', name],
        ['Employee ID', employeeId],
        ['Designation', designation ?? ''],
        ['Date of Join', dateDdMmYyyy(dateOfJoin)],
        ['Period', summary.period],
        ['Total Payouts', String(summary.count)],
        ['Total Amount Paid', bdtNumber(summary.paidMinor)],
        [],
        ['Date', 'Payout Number', 'Amount', 'Method', 'State', 'Source', 'Notes'],
      ];
      for (const row of transactions) {
        lines.push([
          dhakaDateTime(row.createdAt),
          String(row.payoutNumber),
          bdtNumber(row.amountMinor),
          row.method,
          row.state,
          row.source ?? '',
          row.notes ?? '',
        ]);
      }
      lines.push([], [`Generated on ${todayStamp()}`, `Generated by ${generatedBy}`]);
      // The statement has a header block, so build the CSV directly rather
      // than force every row through a fixed column shape.
      const csv = `\uFEFF${lines.map((line) => line
        .map((cell) => /[",\r\n]/.test(cell) ? `"${cell.replaceAll('"', '""')}"` : cell)
        .join(',')).join('\r\n')}\r\n`;
      const blob = new Blob([csv], {type: 'text/csv;charset=utf-8'});
      const url = URL.createObjectURL(blob);
      const anchor = document.createElement('a');
      anchor.href = url;
      anchor.download = `statement_${employeeId}_${todayStamp()}.csv`;
      anchor.click();
      URL.revokeObjectURL(url);
      toast.success(`Statement exported (${transactions.length} transaction(s)).`);
    } catch (error) {
      toast.error(error instanceof Error ? error.message : 'Statement export failed.', {duration: Infinity});
    } finally {
      setBusy(null);
    }
  }

  async function exportPdf() {
    setBusy('pdf');
    try {
      const transactions = await loadTransactions();
      const summary = summaryRows(transactions);
      const [{jsPDF}, autoTableModule] = await Promise.all([
        import('jspdf'),
        import('jspdf-autotable'),
      ]);
      const autoTable = (autoTableModule as unknown as {default: (doc: unknown, options: unknown) => void}).default;
      const doc = new jsPDF({orientation: 'portrait', unit: 'mm', format: 'a4'});
      doc.setFontSize(15);
      doc.text("AL-RIFA'I Platform — Employee Cash Statement", 14, 16);
      doc.setFontSize(9);
      doc.text(`Employee: ${name} (${employeeId})`, 14, 24);
      doc.text(`Designation: ${designation ?? '—'}   Date of Join: ${dateDdMmYyyy(dateOfJoin) || '—'}`, 14, 29);
      doc.text(`Period: ${summary.period}`, 14, 34);
      doc.text(`Total Payouts: ${summary.count}   Total Paid: BDT ${bdtNumber(summary.paidMinor)}`, 14, 39);
      autoTable(doc, {
        startY: 44,
        head: [['Date', 'Payout', 'Amount (BDT)', 'Method', 'State', 'Source', 'Notes']],
        body: transactions.map((row) => [
          dhakaDateTime(row.createdAt),
          String(row.payoutNumber),
          bdtNumber(row.amountMinor),
          row.method,
          row.state,
          row.source ?? '',
          row.notes ?? '',
        ]),
        styles: {fontSize: 7, cellPadding: 1.5, overflow: 'linebreak'},
        headStyles: {fillColor: [15, 76, 99], textColor: 255},
        alternateRowStyles: {fillColor: [244, 247, 250]},
        margin: {left: 14, right: 14},
      });
      const pageHeight = doc.internal.pageSize.getHeight();
      doc.setFontSize(8);
      doc.text(`Generated on ${todayStamp()} · Generated by ${generatedBy}`, 14, pageHeight - 10);
      doc.save(`statement_${employeeId}_${todayStamp()}.pdf`);
      toast.success(`PDF statement generated (${transactions.length} transaction(s)).`);
    } catch (error) {
      toast.error(error instanceof Error ? error.message : 'PDF generation failed.', {duration: Infinity});
    } finally {
      setBusy(null);
    }
  }

  return (
    <div className="statement-export print-hidden">
      <details>
        <summary className="statement-export__trigger">
          <Download className="size-4" /> Download Statement
        </summary>
        <div className="statement-export__menu">
          <button type="button" onClick={() => void exportCsv()} disabled={busy !== null}>
            <Download className="size-4" /> {busy === 'csv' ? 'Preparing CSV…' : 'CSV (UTF-8)'}
          </button>
          <button type="button" onClick={() => void exportPdf()} disabled={busy !== null}>
            <FileText className="size-4" /> {busy === 'pdf' ? 'Preparing PDF…' : 'PDF (A4)'}
          </button>
        </div>
      </details>
      <span className="muted">All transactions{periodLabel(filters) === 'All time' ? '' : ` · ${periodLabel(filters)}`}</span>
    </div>
  );
}
